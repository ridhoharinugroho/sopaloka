-- 2. FTS: Tambah kolom search_vector ke listings
ALTER TABLE public.listings
ADD COLUMN IF NOT EXISTS search_vector tsvector
GENERATED ALWAYS AS (
  setweight(to_tsvector('indonesian', coalesce(title, '')), 'A') ||
  setweight(to_tsvector('indonesian', coalesce(category, '')), 'B') ||
  setweight(to_tsvector('indonesian', coalesce(description, '')), 'C')
) STORED;

CREATE INDEX IF NOT EXISTS listings_search_idx
ON public.listings USING GIN(search_vector);

-- 3. Tabel Perekam Jejak Pencarian (Bahan Bakar AI)
CREATE TABLE IF NOT EXISTS public.search_telemetry (
    id bigint generated by default as identity primary key,
    search_query text NOT NULL,
    clicked_listing_id text REFERENCES public.listings(id),
    created_at timestamptz DEFAULT now() NOT NULL
);

ALTER TABLE public.search_telemetry ENABLE ROW LEVEL SECURITY;

CREATE POLICY "allow_insert_search_telemetry"
ON public.search_telemetry FOR INSERT
WITH CHECK (true);

-- 4. Tabel Kamus Sinonim
CREATE TABLE IF NOT EXISTS public.search_synonyms (
  id bigint generated by default as identity primary key,
  term text NOT NULL,
  synonyms text[] NOT NULL DEFAULT '{}',
  source text NOT NULL DEFAULT 'manual' CHECK (source IN ('manual', 'ai_learned')),
  created_at timestamptz DEFAULT now() NOT NULL,
  updated_at timestamptz DEFAULT now() NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS search_synonyms_term_idx
ON public.search_synonyms(lower(term));

ALTER TABLE public.search_synonyms ENABLE ROW LEVEL SECURITY;

CREATE POLICY "allow_read_synonyms"
ON public.search_synonyms FOR SELECT
USING (true);

