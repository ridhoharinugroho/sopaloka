-- 6. AI SQL Function: Belajar Sinonim dari Telemetry
CREATE OR REPLACE FUNCTION public.learn_synonyms_from_telemetry()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  rec RECORD;
  pair_count integer := 0;
BEGIN
  FOR rec IN
    WITH clicks_per_listing AS (
      SELECT
        lower(trim(search_query)) AS query,
        clicked_listing_id,
        COUNT(*) AS click_count
      FROM public.search_telemetry
      WHERE clicked_listing_id IS NOT NULL
        AND created_at > now() - interval '30 days'
        AND length(trim(search_query)) >= 3
      GROUP BY lower(trim(search_query)), clicked_listing_id
      HAVING COUNT(*) >= 3
    ),
    synonym_candidates AS (
      SELECT
        a.query AS term_a,
        b.query AS term_b,
        COUNT(DISTINCT a.clicked_listing_id) AS shared_listings
      FROM clicks_per_listing a
      JOIN clicks_per_listing b
        ON a.clicked_listing_id = b.clicked_listing_id
        AND a.query < b.query
      GROUP BY a.query, b.query
      HAVING COUNT(DISTINCT a.clicked_listing_id) >= 2
    )
    SELECT term_a, term_b FROM synonym_candidates
  LOOP
    INSERT INTO public.search_synonyms (term, synonyms, source)
    VALUES (rec.term_a, ARRAY[rec.term_b], 'ai_learned')
    ON CONFLICT (lower(term)) DO UPDATE
      SET synonyms = (
        SELECT ARRAY(SELECT DISTINCT unnest(search_synonyms.synonyms || ARRAY[rec.term_b]))
      ),
      updated_at = now(),
      source = CASE WHEN search_synonyms.source = 'manual' THEN 'manual' ELSE 'ai_learned' END;

    INSERT INTO public.search_synonyms (term, synonyms, source)
    VALUES (rec.term_b, ARRAY[rec.term_a], 'ai_learned')
    ON CONFLICT (lower(term)) DO UPDATE
      SET synonyms = (
        SELECT ARRAY(SELECT DISTINCT unnest(search_synonyms.synonyms || ARRAY[rec.term_a]))
      ),
      updated_at = now(),
      source = CASE WHEN search_synonyms.source = 'manual' THEN 'manual' ELSE 'ai_learned' END;

    pair_count := pair_count + 1;
  END LOOP;

  RAISE NOTICE '[learn_synonyms] Selesai. % pasang sinonim baru ditemukan.', pair_count;
END;
$$;

